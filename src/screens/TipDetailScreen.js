import React, { useState, useEffect } from 'react';
import { View, StyleSheet, ScrollView, TouchableOpacity, Dimensions, Share, Alert } from 'react-native';
import { Feather, MaterialCommunityIcons } from '@expo/vector-icons';
import * as Speech from 'expo-speech';
import Screen from '../components/Screen';
import AppText from '../components/AppText';
import { useLanguage } from '../context/LanguageContext';
import { useTheme } from '../context/ThemeContext';

const { width } = Dimensions.get('window');

export default function TipDetailScreen({ route, navigation }) {
    const { colors, isDarkMode } = useTheme();
    const { t, language } = useLanguage();
    const styles = React.useMemo(() => getStyles(colors, isDarkMode), [colors, isDarkMode]);
    const { tip } = route.params || {};
    const [isSpeaking, setIsSpeaking] = useState(false);

    // Stop speaking when user exits the screen
    useEffect(() => {
        return () => {
            Speech.stop();
        };
    }, []);

    const toggleSpeech = async () => {
        try {
            const isDictating = await Speech.isSpeakingAsync();
            if (isDictating || isSpeaking) {
                Speech.stop();
                setIsSpeaking(false);
            } else {
                setIsSpeaking(true);
                // Strip markdown formatting symbols without stripping non-Latin unicode characters
                let titleText = tip.title || '';
                let contentText = tip.content || '';
                let fullText = `${titleText}. ${contentText}`.replace(/[*#_~`]/g, '');

                const SPEECH_LANG_MAP = {
                    kn: 'kn-IN',
                    ml: 'ml-IN',
                    hi: 'hi-IN',
                    ta: 'ta-IN',
                    te: 'te-IN',
                    tu: 'kn-IN',
                    ar: 'kn-IN',
                    en: 'en-IN'
                };
                const speechLocale = SPEECH_LANG_MAP[language] || 'en-US';

                // Break text into sentences to prevent Android TTS buffer overflow
                const sentences = fullText.split(/[\.\n।]/).map(s => s.trim()).filter(s => s.length > 0);

                if (sentences.length === 0) {
                    setIsSpeaking(false);
                    return;
                }

                sentences.forEach((sentence, index) => {
                    Speech.speak(sentence, {
                        language: speechLocale,
                        rate: 0.9,
                        onDone: () => {
                            if (index === sentences.length - 1) setIsSpeaking(false);
                        },
                        onStopped: () => {
                            if (index === sentences.length - 1) setIsSpeaking(false);
                        },
                        onError: (e) => {
                            console.error("TTS Error:", e);
                            if (index === sentences.length - 1) setIsSpeaking(false);
                        }
                    });
                });
            }
        } catch (err) {
            console.error("Speech init err", err);
            setIsSpeaking(false);
        }
    };

    const handleShare = async () => {
        try {
            const message = `🌱 ArecaCare AI Advisory\n\n*${t(tip.title) || tip.title}*\n${tip.content}\n\nGenerated by ArecaCare AI`;
            await Share.share({
                message: message,
                title: t(tip.title) || tip.title,
            });
        } catch (error) {
            console.error("Share failed", error);
            Alert.alert(t('error'), "Could not share the advisory link.");
        }
    };

    if (!tip) {
        return (
            <Screen style={styles.screen}>
                <AppText style={{ color: colors.text }}>{t('error')}</AppText>
            </Screen>
        );
    }

    return (
        <Screen style={styles.screen} noPadding>
            <View style={styles.header}>
                <TouchableOpacity onPress={() => navigation.goBack()} hitSlop={{ top: 10, bottom: 10, left: 10, right: 10 }}>
                    <Feather name="chevron-left" size={28} color={colors.text} />
                </TouchableOpacity>
                <AppText variant="heading3" style={{ color: colors.text }}>{t('farming_tips')}</AppText>
                <View style={styles.rightActions}>
                    <TouchableOpacity
                        onPress={toggleSpeech}
                        hitSlop={{ top: 10, bottom: 10, left: 10, right: 10 }}
                        style={[styles.headerIconBtn, isSpeaking && styles.activeSpeechBtn]}
                    >
                        <Feather name={isSpeaking ? "volume-x" : "volume-2"} size={22} color={isSpeaking ? "#FFFFFF" : colors.text} />
                    </TouchableOpacity>
                    <TouchableOpacity onPress={handleShare} hitSlop={{ top: 10, bottom: 10, left: 10, right: 10 }} style={styles.headerIconBtn}>
                        <Feather name="share-2" size={22} color={colors.text} />
                    </TouchableOpacity>
                </View>
            </View>

            <ScrollView style={styles.scrollRoot} showsVerticalScrollIndicator={false} contentContainerStyle={styles.content}>
                <View style={styles.iconHeroCard}>
                    <View style={styles.iconBadge}>
                        <MaterialCommunityIcons name={tip.icon || 'leaf'} size={48} color={colors.primary} />
                    </View>
                </View>

                {/* Content Body */}
                <View style={styles.articleBody}>
                    <View style={styles.metaRow}>
                        <View style={styles.pill}>
                            <AppText variant="caption" style={styles.pillText}>
                                {(t(tip.category) || tip.category || 'ADVISORY')?.toUpperCase()}
                            </AppText>
                        </View>
                        <View style={styles.timeWrapper}>
                            <Feather name="clock" size={14} color={colors.textMedium} />
                            <AppText variant="caption" style={styles.timeText}>
                                {t(tip.readTime) || tip.readTime}
                            </AppText>
                        </View>
                    </View>

                    <AppText variant="heading2" style={styles.title}>
                        {t(tip.title) || tip.title}
                    </AppText>

                    <View style={styles.divider} />

                    {tip.content.split('\n').map((paragraph, index) => (
                        paragraph.trim() ? (
                            <AppText key={index} variant="bodyMedium" style={styles.paragraph}>
                                {paragraph.trim()}
                            </AppText>
                        ) : null
                    ))}
                </View>
            </ScrollView>
        </Screen>
    );
}

